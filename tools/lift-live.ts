/* Run the live beat's assertions on a machine with no MSVC.
 *
 *     bun tools/lift-live.ts
 *
 * `cargo test` cannot link here, and `flyway-core`'s own suite pulls `iroh`,
 * which fails to link on the gnu toolchain before any test runs. The module
 * this lifts is pure — `serde` and `clip` and nothing else — so its own
 * assertions are the one part of a change to it that can be executed here.
 *
 * What is checked, and why it is not readable by eye: that a beat survives the
 * wire it is written for, and that a number which is not one is sent as zero
 * rather than as itself. The second is not tidiness. `serde_json` refuses a
 * NaN, so a beat carrying one is a frame that never leaves, and the wall that
 * computed it looks dark to every peer for a reason nothing reports.
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { coherentRlibs, depsDir, newestRlib, rustEnv } from "./lift-scan.ts";

const LIVE = "src-tauri/flyway-core/src/live.rs";
const FRAME = "src-tauri/flyway-core/src/frame.rs";
const CLIP = "src-tauri/flyway-core/src/clip.rs";
const CLEAN = "src-tauri/flyway-core/src/clean.rs";
const DEPS = depsDir();
const HOST = "src-tauri/target/debug/deps";

const read = (p: string) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");

/* `live.rs` names `crate::frame::Frame` in one assertion, so the lift carries a
   stand-in for the envelope: the one variant the test builds and compares,
   which is the whole of what a round trip through the wire has to show. */
const lift = [
  "// GENERATED by tools/lift-live.ts — do not edit, do not keep.",
  "mod clean {",
  read(CLEAN),
  "}",
  "mod clip {",
  read(CLIP),
  "}",
  "pub mod frame {",
  "use serde::{Deserialize, Serialize};",
  "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]",
  "#[serde(untagged)]",
  "pub enum Frame { Live(crate::live::LiveMsg) }",
  "}",
  "pub mod live {",
  read(LIVE),
  "}",
  "pub use live::*;",
].join("\n");

const dir = mkdtempSync(join(tmpdir(), "lift-live-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, lift);

function run(exe: string): ReturnType<typeof spawnSync> {
  for (let go = 0; go < 5; go++) {
    const got = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
    if (got.error && (got.error as NodeJS.ErrnoException).code === "EPERM") continue;
    return got;
  }
  return spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
}

try {
  const borrowed = coherentRlibs(["serde", "serde_json"]);
  const build = spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "--crate-name",
      "live",
      "-A",
      "dead_code",
      "--extern",
      `serde=${borrowed.serde}`,
      "--extern",
      `serde_json=${borrowed.serde_json}`,
      "-L",
      `dependency=${DEPS}`,
      "-L",
      `dependency=${HOST}`,
      file,
      "-o",
      exe,
    ],
    { encoding: "utf8", env: rustEnv() },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const got = run(exe);
  console.log(got.stdout);
  if (got.stderr) console.error(got.stderr);
  try {
    rmSync(dir, { recursive: true, force: true });
  } catch {
    /* The EDR holds the exe; the directory is in `%TEMP%`. Never a red lift. */
  }
  process.exit(got.status ?? 1);
} catch (e) {
  console.error(e);
  process.exit(1);
}
