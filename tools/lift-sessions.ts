/* Actually run the prompt filter's assertions, on a machine that cannot link the
 * crate.
 *
 *     bun tools/lift-sessions.ts
 *
 * `.claude/rules/build.md` has the whole of why `cargo test` does not run here,
 * and this is the half of phase 5a's suite that *can* be executed: `sessions.rs`
 * carries four suites that need a real transcript on disk (and `store::uuid_v4`),
 * and the rest of it, the fold that decides whether a `user` record is somebody
 * speaking, needs nothing but `serde_json`.
 *
 * **That fold is the one rule the whole prompt lane is built on.** `prompt_of`
 * sits on top of it, the titling grid reads the same answer, and the ingest
 * counts what the rest of the file is instead. A partition claim — §3.8's table
 * of nine rejection classes that sums to the total — is exactly the kind of
 * thing that compiles perfectly and is wrong, so it is worth running.
 *
 * Nothing is kept, for the reason every `lift-*.ts` here gives.
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { blockAt, depsDir, newestRlib, rustEnv } from "./lift-scan.ts";

const SESSIONS = "src-tauri/src/sessions.rs";

/** The declarations, in an order that lets each name be found when it is used.
 *  Listed as what comes *in* rather than what stays out: a new pure function in
 *  this file and not here is simply untested, which is quiet. */
const ITEMS: string[] = [
  "const PROMPT_CLIP",
  "const MAX_PROMPT_BYTES",
  "fn without_tag",
  "enum Why",
  "const INJECTED",
  "const WALL",
  "fn resend_marked",
  "enum Folded",
  "fn carries_text",
  "fn fold",
  "fn prompt_of",
  "fn clip",
];

const TESTS: string[] = [
  /* The partition, one record per class, and the order that makes it one. */
  "each_user_record_reaches_exactly_one_class",
  /* The wall's own words, dropped rather than counted. */
  "the_wall_speaking_is_not_somebody_speaking",
  /* The gate on a record's shape must not reject prose that names it. */
  "prose_about_the_format_is_still_a_prompt",
  /* The reason the fold exists at all: the form keeps the lines and fences. */
  "a_fenced_prompt_keeps_its_lines_for_the_form_and_loses_them_for_a_title",
  "image_blocks_are_counted_and_their_bytes_are_not",
  /* `prompt_of`'s own behaviour, unchanged by the split. */
  "injected_context_is_not_something_anybody_said",
];

const lines = readFileSync(SESSIONS, "utf8").split(/\r?\n/);

function testsAt(): number {
  const at = lines.findIndex((l) => /^\s*mod tests\s*\{/.test(l));
  if (at < 0) throw new Error(`no test module in ${SESSIONS}`);
  return at;
}

function find(what: string): string {
  const stop = testsAt();
  const re = new RegExp(`^\\s*(pub(\\([a-z]+\\))?\\s+)?${what.replace(/ /g, "\\s+")}\\b`);
  for (let i = 0; i < stop; i++) {
    if (re.test(lines[i])) return blockAt(lines, i, SESSIONS);
  }
  throw new Error(`could not find "${what}" in ${SESSIONS} — has it been renamed?`);
}

function findTest(name: string): string {
  for (let i = testsAt(); i < lines.length; i++) {
    if (new RegExp(`^\\s*fn ${name}\\s*\\(`).test(lines[i])) return blockAt(lines, i, SESSIONS);
  }
  throw new Error(`could not find test "${name}" in ${SESSIONS} — has it been renamed?`);
}

const body = [
  "//! GENERATED by tools/lift-sessions.ts — do not edit, do not keep.",
  ...ITEMS.map(find),
  "#[cfg(test)]",
  "mod tests {",
  "    use super::*;",
  ...TESTS.map(findTest),
  "}",
].join("\n\n");

const dir = mkdtempSync(join(tmpdir(), "lift-sessions-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, body);

try {
  const build = spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "-A",
      "dead_code",
      "--extern",
      `serde_json=${newestRlib("serde_json")}`,
      "-L",
      `dependency=${depsDir()}`,
      file,
      "-o",
      exe,
    ],
    /* Bare `rustc` takes the msvc default toolchain here and dies on
       `link: extra operand`, which names nothing that points at the cause. */
    { encoding: "utf8", env: rustEnv() },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file}, and it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const run = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
  console.log(run.stdout);
  if (run.stderr) console.error(run.stderr);
  process.exit(run.status ?? 1);
} finally {
  try {
    rmSync(exe, { force: true });
  } catch {
    /* the exe may still be held; the temp dir goes either way */
  }
}
