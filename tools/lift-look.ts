/* Actually run `flyway/look.rs`'s assertions on a machine with no MSVC.
 *
 *     bun tools/lift-look.ts
 *
 * `look.rs` is how a question asked on one wall shows its screenshots and
 * designs on another: the owning wall's answer, the asking wall's gathering
 * of the parts, and the rewrite that points every file slot at what arrived —
 * or at a fault, and never at a path the other machine wrote. Every one of
 * those is a bug that compiles, and the file is pure by construction (the disk
 * is a trait), so it is lifted **whole** and a test added to it is run rather
 * than quietly skipped.
 *
 * What it reaches in the crate, lifted verbatim rather than restated so a
 * change there is a change to what this runs: `ask::each_site` (the one walk
 * both walls number files by), `ask::scrub_json`, `ask::MAX_FILES`,
 * `clean::scrub`, and `base64`/`unbase64` from `lib.rs`.
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { blockAt, depsDir, newestRlib, rustEnv } from "./lift-scan.ts";

const LOOK = "src-tauri/src/flyway/look.rs";
const ASK = "src-tauri/src/ask.rs";
const CLEAN = "src-tauri/src/clean.rs";
const LIB = "src-tauri/src/lib.rs";
const DEPS = depsDir();
const HOST = "src-tauri/target/debug/deps";

const read = (p: string) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");

/** One declaration out of `file`, found by the start of its head line and
 *  asserted, so a rename is loud rather than a lift with a hole in it. */
function take(file: string, head: string): string {
  const lines = read(file).split("\n");
  const i = lines.findIndex((l) => l.startsWith(head));
  if (i === -1) throw new Error(`${file} no longer has \`${head}\` — has it been renamed?`);
  return blockAt(lines, i, file);
}

const lift = [
  read(LOOK),
  "",
  "// GENERATED by tools/lift-look.ts — do not edit, do not keep.",
  take(LIB, "pub(crate) fn base64("),
  take(LIB, "pub(crate) fn unbase64("),
  "mod ask {",
  "use serde_json::Value;",
  take(ASK, "pub(crate) const MAX_FILES"),
  take(ASK, "pub(crate) fn each_site<"),
  take(ASK, "pub(crate) fn scrub_json("),
  "}",
  "mod clean {",
  "use std::borrow::Cow;",
  take(CLEAN, "pub fn impossible("),
  take(CLEAN, "pub fn scrub("),
  "}",
].join("\n");

const dir = mkdtempSync(join(tmpdir(), "lift-look-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, lift);

try {
  const build = spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "--crate-name",
      "look",
      "-A",
      "dead_code",
      "--extern",
      `serde=${newestRlib("serde")}`,
      "--extern",
      `serde_json=${newestRlib("serde_json")}`,
      "-L",
      `dependency=${DEPS}`,
      "-L",
      `dependency=${HOST}`,
      file,
      "-o",
      exe,
    ],
    /* Bare `rustc` takes the msvc default and dies on `link: extra operand`,
       which names nothing (sink b282b54c). */
    { encoding: "utf8", env: rustEnv() },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const run = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
  console.log(run.stdout);
  if (run.stderr) console.error(run.stderr);
  rmSync(dir, { recursive: true, force: true });
  process.exit(run.status ?? 1);
} catch (e) {
  console.error(e);
  process.exit(1);
}
