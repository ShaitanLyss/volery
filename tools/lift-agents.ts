/* Actually run the agent writer's assertions on a machine with no MSVC.
 *
 *     bun tools/lift-agents.ts
 *
 * ### What is checked, and why reading it is not enough
 *
 * `analytics_agent` is written by an **additive upsert**, from chunks that
 * arrive out of order and overlap. That arithmetic has two ways to be wrong and
 * neither throws: a row replaced instead of added loses every bucket but the
 * last, and a row added to when it should be replaced doubles a cost that then
 * appears in a total somebody is reconciling against a bill.
 *
 * It also writes the **cost down at fold time** (§4.4), which is the one number
 * on this wall that a later rate change must not move. The tests below are about
 * the row's arithmetic, not about the price: the price itself is
 * `spend::rules::price`, tested where it lives.
 *
 * The block carries its own tests between the `LIFT-BEGIN` and `LIFT-END`
 * markers, and this compiles them with the real `analytics_agent` schema
 * restated for an in-memory database (the table itself is the crate's, and
 * `analytics_agent`'s five columns for `spawn_info` are stubbed with the real
 * SELECT's columns only, which is stated in the test's own header).
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { depsDir, newestRlib, rustEnv } from "./lift-scan.ts";

const ANALYTICS = "src-tauri/src/analytics.rs";
const STORE = "src-tauri/src/store.rs";
const CLIP = "src-tauri/flyway-core/src/clip.rs";
const CLEAN = "src-tauri/flyway-core/src/clean.rs";
const DEPS = depsDir();
const HOST = "src-tauri/target/debug/deps";

const read = (p: string) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");

function agentsBlock(): string {
  const src = read(ANALYTICS);
  const begin = src.indexOf("/* LIFT-BEGIN agents");
  const end = src.indexOf("/* LIFT-END agents */");
  if (begin < 0 || end < 0) throw new Error(`no LIFT markers in ${ANALYTICS} — were they removed?`);
  if (end < begin) throw new Error(`LIFT-END comes before LIFT-BEGIN in ${ANALYTICS}`);
  const after = src.indexOf("*/", begin);
  if (after < 0 || after > end) throw new Error(`LIFT-BEGIN's comment is unterminated`);
  return src.slice(after + 2, end);
}

/** **The table the lift stands up must be the table the store has.**
 *
 *  This is the guard that would have caught a blocker: the stand-in was
 *  restated with a two-column primary key, so the writer's
 *  `ON CONFLICT(agent_id, session)` matched it and every assertion passed,
 *  while against the real three-column key SQLite refuses the statement at
 *  prepare and the whole analytics pass rolls back. A false green is worse
 *  than no lift, so the two texts are compared before anything compiles.
 *
 *  The store's shape is the `CREATE TABLE` in `store.rs` plus the `profile`
 *  column rung 72 adds by `ALTER`, so the stand-in is checked with that line
 *  taken back out. */
function ddlAgrees(): void {
  const store = read(STORE);
  const at = store.indexOf("CREATE TABLE IF NOT EXISTS analytics_agent (");
  if (at < 0) throw new Error("no analytics_agent in store.rs — has it been renamed?");
  const real = store.slice(at, store.indexOf(");", at) + 2);

  const src = read(ANALYTICS);
  const mine = src.slice(
    src.indexOf("CREATE TABLE analytics_agent ("),
    src.indexOf(");", src.indexOf("CREATE TABLE analytics_agent (")) + 2,
  );
  const norm = (s: string) => s.replace(/\s+/g, " ").trim();
  const withoutProfile = norm(mine.replace(/profile\s+TEXT NOT NULL DEFAULT '',/, ""));
  const expected = norm(real);
  if (withoutProfile.replace("CREATE TABLE analytics_agent", "CREATE TABLE IF NOT EXISTS analytics_agent") !== expected) {
    console.error(
      "the agent tests' stand-in table has drifted from store.rs's:\n\n" +
        `store.rs:    ${expected}\n\nanalytics.rs: ${withoutProfile}\n\n` +
        "They must match, key included: a conflict target that fits one and not the other is a " +
        "writer that fails every pass and a lift that goes green anyway.",
    );
    process.exit(1);
  }
}

ddlAgrees();

const lift = [
  "// GENERATED by tools/lift-agents.ts — do not edit, do not keep.",
  "use rusqlite::{params, Connection};",
  "use std::collections::HashMap;",
  "mod clean {",
  read(CLEAN),
  "}",
  "mod clip {",
  read(CLIP),
  "}",
  /* The one constant the block reads, and the grain §3.1 sets. */
  "pub(crate) const BUCKET_MS: i64 = 5 * 60 * 1000;",
  agentsBlock(),
].join("\n");

const dir = mkdtempSync(join(tmpdir(), "lift-agents-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, lift);

/* The EDR on this machine refuses a fresh exe out of `%TEMP%` the first time
   and refuses to remove a directory holding one. Retried and best-effort, the
   same pair `tools/lift-rollups.ts` carries for the same reason. */
function run(exe: string): ReturnType<typeof spawnSync> {
  for (let go = 0; go < 5; go++) {
    const got = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
    if (got.error && (got.error as NodeJS.ErrnoException).code === "EPERM") continue;
    return got;
  }
  return spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
}

try {
  const build = spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "--crate-name",
      "agents",
      "-A",
      "dead_code",
      "--extern",
      `rusqlite=${newestRlib("rusqlite")}`,
      "-L",
      `dependency=${DEPS}`,
      "-L",
      `dependency=${HOST}`,
      file,
      "-o",
      exe,
    ],
    /* Load-bearing: bare `rustc` takes the msvc default and dies on
       `link: extra operand`, which names nothing (sink b282b54c). */
    { encoding: "utf8", env: rustEnv() },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const got = run(exe);
  console.log(got.stdout);
  if (got.stderr) console.error(got.stderr);
  try {
    rmSync(dir, { recursive: true, force: true });
  } catch {
    /* The EDR holds the exe; the directory is in `%TEMP%`. Never a red lift. */
  }
  process.exit(got.status ?? 1);
} catch (e) {
  console.error(e);
  process.exit(1);
}
