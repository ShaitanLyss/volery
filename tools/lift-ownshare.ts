/* Run the door's own assertions on a machine with no MSVC.
 *
 *     bun tools/lift-ownshare.ts
 *
 * `cargo test` cannot link here, and the half of `ownshare.rs` worth asserting
 * is pure — `serde_json` and nothing else — so it lives in its own file
 * (`src-tauri/src/ownshare/share.rs`) and is compiled here verbatim.
 *
 * What is checked, and why it is not readable by eye: that a ceiling is
 * measured on **your own share** and never on the account's percentage, and
 * that a share with nothing priced under it holds nothing back. Both are the
 * difference between a cap that answers "somebody else used 20% of your
 * subscription" and one that spends a reserve you meant to keep.
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { depsDir, newestRlib, rustEnv } from "./lift-scan.ts";

const SHARE = "src-tauri/src/ownshare/share.rs";
const DEPS = depsDir();
const HOST = "src-tauri/target/debug/deps";

const lift = [
  "// GENERATED by tools/lift-ownshare.ts — do not edit, do not keep.",
  readFileSync(SHARE, "utf8").replace(/\r\n/g, "\n"),
].join("\n");

const dir = mkdtempSync(join(tmpdir(), "lift-ownshare-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, lift);

function run(exe: string): ReturnType<typeof spawnSync> {
  for (let go = 0; go < 5; go++) {
    const got = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
    if (got.error && (got.error as NodeJS.ErrnoException).code === "EPERM") continue;
    return got;
  }
  return spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
}

try {
  const build = spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "--crate-name",
      "ownshare",
      "-A",
      "dead_code",
      "--extern",
      `serde=${newestRlib("serde")}`,
      "--extern",
      `serde_json=${newestRlib("serde_json")}`,
      "-L",
      `dependency=${DEPS}`,
      "-L",
      `dependency=${HOST}`,
      file,
      "-o",
      exe,
    ],
    { encoding: "utf8", env: rustEnv() },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const got = run(exe);
  console.log(got.stdout);
  if (got.stderr) console.error(got.stderr);
  try {
    rmSync(dir, { recursive: true, force: true });
  } catch {
    /* The EDR holds the exe; the directory is in `%TEMP%`. Never a red lift. */
  }
  process.exit(got.status ?? 1);
} catch (e) {
  console.error(e);
  process.exit(1);
}
