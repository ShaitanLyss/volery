/* Actually run the prompt classifier's assertions, on a machine that cannot
 * link the crate.
 *
 *     bun tools/lift-prompt.ts
 *
 * `.claude/rules/build.md` has the whole of why `cargo test` does not run here.
 * The classifier is a list of ordered rules and the only way to know whether one
 * of them fires before the one it was written ahead of is to run a prompt
 * through it, so compiling is not evidence of anything here.
 *
 * **Two files, because `prompt.rs` reaches for one thing in `redact.rs`**: the
 * fence scanner, shared so that the form's `code_lines` and the redactor's
 * `<code omitted: N lines>` cannot disagree about what a fence is. So the lift
 * lays both modules down as siblings and gives rustc a root that declares them;
 * `crate::redact::fence_blocks` then resolves exactly as it does in the app.
 *
 * That one `crate::` call is worth knowing about: it is the shape `.claude/rules/
 * build.md` warns rots a lift, because the lift's item lists can drift from the
 * module. This lift names no items at all (both files are compiled whole), so
 * there is nothing to drift, and a new `crate::` import in `prompt.rs` fails
 * loudly here rather than silently going untested.
 *
 * Only `prompt::` tests are run: `redact.rs` brings its own corpora with it and
 * `tools/lift-redact.ts` runs those, so this filter keeps one failure pointing
 * at one module.
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { rustEnv } from "./lift-scan.ts";

const MODULES = ["redact", "prompt"] as const;

const dir = mkdtempSync(join(tmpdir(), "lift-prompt-"));
const root = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");

for (const m of MODULES) {
  writeFileSync(join(dir, `${m}.rs`), readFileSync(`src-tauri/src/${m}.rs`, "utf8"));
}
writeFileSync(
  root,
  `//! GENERATED by tools/lift-prompt.ts, do not edit, do not keep.\n${MODULES.map(
    (m) => `mod ${m};`,
  ).join("\n")}\n`,
);

try {
  const build = spawnSync(
    "rustc",
    ["--test", "--edition", "2021", "-A", "dead_code", root, "-o", exe],
    /* Bare `rustc` takes the msvc default toolchain here and dies on
       `link: extra operand`, which names nothing that points at the cause. */
    { encoding: "utf8", env: rustEnv() },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${dir}, and it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const run = spawnSync(exe, ["--test-threads", "1", "prompt::tests"], { encoding: "utf8" });
  console.log(run.stdout);
  if (run.stderr) console.error(run.stderr);
  process.exit(run.status ?? 1);
} finally {
  try {
    rmSync(exe, { force: true });
  } catch {
    /* the exe may still be held; the temp dir goes either way */
  }
}
