/* Actually run the fleet's rollup assertions on a machine with no MSVC.
 *
 *     bun tools/lift-rollups.ts
 *
 * `cargo test` does not link here (`.claude/rules/build.md`), so
 * `tools/check-gnu.sh --all-targets` *typechecks* `flyway-core/src/analytics.rs`'s
 * assertions and runs none of them. This runs them.
 *
 * ### Why this one earns a lift
 *
 * Everything in that file is a claim that cannot be checked by reading it. A
 * day's digest must be the same on two walls that hold the same rows in a
 * different order, and different when one number moved; a calendar conversion
 * must be an exact inverse over fifty years, including the leap rules a naive
 * `/4` gets wrong; and a frame that does not match its own digest must be
 * refused whole rather than stored as a day nobody can tell is short. A wrong
 * answer in any of them does not fail — it splits one day across two walls and
 * leaves both totals wrong, quietly, which is the failure the digest exists to
 * make impossible.
 *
 * The file is pure: `clip` and `clean` are the only things it reaches, and both
 * have no dependencies of their own beyond `std`. So it is lifted **whole**,
 * its own test module included, and a test added to it is run rather than
 * quietly skipped.
 *
 * What it borrows: `serde`, `serde_json` and `ring` out of the gnu target
 * directory, and the `serde_derive` proc-macro out of the host one, exactly as
 * `lift-fleet.ts` does.
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { coherentRlibs, depsDir, newestRlib, rustEnv } from "./lift-scan.ts";

const ANALYTICS = "src-tauri/flyway-core/src/analytics.rs";
const CLIP = "src-tauri/flyway-core/src/clip.rs";
const CLEAN = "src-tauri/flyway-core/src/clean.rs";
const DEPS = depsDir();
const HOST = "src-tauri/target/debug/deps";

const read = (p: string) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");

/* `clip` and `clean` whole, tests and all: they are two modules with nothing
   above them, `lift-clip.ts` runs the same two files for the same reason, and
   running their assertions again here costs a second and keeps this lift from
   having to decide which half of them `analytics.rs` uses. */
/* `analytics.rs` is wrapped rather than pasted at the root, because its own
   `use crate::clip;` and a root `mod clip` are the same name in the same
   namespace. Inside a module the absolute path still resolves to the root. */
const lift = [
  "// GENERATED by tools/lift-rollups.ts — do not edit, do not keep.",
  "mod clean {",
  read(CLEAN),
  "}",
  "mod clip {",
  read(CLIP),
  "}",
  "mod rollups {",
  read(ANALYTICS),
  "}",
].join("\n");

const dir = mkdtempSync(join(tmpdir(), "lift-rollups-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, lift);

try {
  const borrowed = coherentRlibs(["serde", "serde_json", "ring"]);
  const build = spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "--crate-name",
      "rollups",
      "-A",
      "dead_code",
      "--extern",
      `serde=${borrowed.serde}`,
      "--extern",
      `serde_json=${borrowed.serde_json}`,
      "--extern",
      `ring=${borrowed.ring}`,
      "-L",
      `dependency=${DEPS}`,
      "-L",
      `dependency=${HOST}`,
      file,
      "-o",
      exe,
    ],
    /* Load-bearing, as in every lift: bare `rustc` takes the msvc default and
       dies on `link: extra operand`, which names nothing (sink b282b54c). */
    { encoding: "utf8", env: rustEnv() },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const run = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
  console.log(run.stdout);
  if (run.stderr) console.error(run.stderr);
  rmSync(dir, { recursive: true, force: true });
  process.exit(run.status ?? 1);
} catch (e) {
  console.error(e);
  process.exit(1);
}
