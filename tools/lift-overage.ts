/* Actually run the usage-credit assertions in `limits.rs` on a machine with no
 * MSVC.
 *
 * `cargo test` does not exist here — `.claude/rules/build.md` has the whole of
 * why. So a typecheck is the most a no-MSVC card can say about `limits.rs`'s
 * tests, and these are the ones where a typecheck says nothing that matters:
 *
 *     bun tools/lift-overage.ts
 *
 * **What is worth executing.** `credits_left` is a sentence about money handed
 * to an agent, and its two ways of being wrong both compile: the divisor (minor
 * units are cents for dollars and *whole* yen, so `/ 100.0` everywhere reads a
 * Japanese balance a hundred times too small), and the edge where nothing is
 * left, which must be silence rather than "0.00 USD left". And `Overage` is the
 * type every other wall's reading is deserialized through (`afar_report`): a
 * field added without being optional would make an older wall's whole reading
 * fail to parse, which is a flyway quietly losing its shared allowances.
 *
 * It regenerates from `limits.rs` on every run and keeps nothing, for the reason
 * every `lift-*.ts` gives: a copy that can go stale will, and goes on passing.
 * The items are listed by what comes *in*, so a new pure helper these call and
 * that is not added here fails loudly at compile rather than passing quietly.
 */

import { readFileSync, readdirSync, statSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { blockAt, depsDir, newestRlib, rustEnv } from "./lift-scan.ts";

const LIMITS = "src-tauri/src/limits.rs";
const HOST = "src-tauri/target/debug/deps";

const ITEMS: string[] = [
  "struct Overage",
  "fn text",
  "fn percent",
  "fn amount",
  "fn overage",
  "fn credits_left",
];

const TESTS: string[] = [
  "overage_is_read_when_the_account_has_it",
  "credits_left_are_read_in_minor_units",
  "an_overage_without_amounts_still_deserializes",
];

const lines = readFileSync(LIMITS, "utf8").split(/\r?\n/);
const block = (i: number): string => blockAt(lines, i, LIMITS);

function testsAt(): number {
  const at = lines.findIndex((l) => /^\s*mod tests\s*\{/.test(l));
  if (at < 0) throw new Error(`no test module in ${LIMITS}`);
  return at;
}

function find(what: string): string {
  const stop = testsAt();
  const re = new RegExp(`^\\s*(pub(\\([a-z]+\\))?\\s+)?${what.replace(/ /g, "\\s+")}\\b`);
  for (let i = 0; i < stop; i++) {
    if (re.test(lines[i])) return block(i);
  }
  throw new Error(`could not find "${what}" in ${LIMITS} — has it been renamed?`);
}

function findTest(name: string): string {
  for (let i = testsAt(); i < lines.length; i++) {
    if (new RegExp(`^\\s*fn ${name}\\s*\\(`).test(lines[i])) return block(i);
  }
  throw new Error(`could not find test "${name}" in ${LIMITS} — has it been renamed?`);
}

const body = [
  "//! GENERATED by tools/lift-overage.ts — do not edit, do not keep.",
  "use serde::{Deserialize, Serialize};",
  ...ITEMS.map(find),
  "#[cfg(test)]",
  "mod tests {",
  "    use super::*;",
  ...TESTS.map(findTest),
  "}",
].join("\n\n");

const dir = mkdtempSync(join(tmpdir(), "lift-overage-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, body);

/* Every `serde` and `serde_json` rlib in the deps directory, newest first.
 *
 * `newestRlib` alone is not enough here, and measured so on 2026-10-29: the
 * directory held six `serde` and four `serde_json` builds from different
 * feature sets, and the newest of each were built against different
 * `serde_core`s — so `#[derive(Serialize)]` compiled against one trait and
 * `to_value` asked for the other (`E0277 … Overage: serde::Serialize`).
 * `lift-fleet.ts` fails the same way on the same tree. So the pair is found
 * by asking rustc, newest `serde_json` first, which is a few seconds at worst
 * and is the one answer that cannot be stale. */
function rlibs(name: string): string[] {
  const dir = depsDir();
  const re = new RegExp(`^lib${name}-[0-9a-f]+\\.rlib$`);
  return readdirSync(dir)
    .filter((f) => re.test(f))
    .map((f) => join(dir, f))
    .sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs);
}

function compile(serde: string, json: string) {
  return spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "--crate-name",
      "overage",
      "-A",
      "dead_code",
      "--extern",
      `serde=${serde}`,
      "--extern",
      `serde_json=${json}`,
      "-L",
      `dependency=${depsDir()}`,
      "-L",
      `dependency=${HOST}`,
      file,
      "-o",
      exe,
    ],
    /* Load-bearing, as in every lift: bare `rustc` takes the msvc default and
       dies on `link: extra operand`, which names nothing (sink b282b54c). */
    { encoding: "utf8", env: rustEnv() },
  );
}

let build = compile(newestRlib("serde"), newestRlib("serde_json"));
pairing: for (const json of rlibs("serde_json")) {
  if (build.status === 0) break;
  for (const serde of rlibs("serde")) {
    build = compile(serde, json);
    if (build.status === 0) break pairing;
  }
}
if (build.status !== 0) {
  console.error(build.stderr || build.stdout);
  console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
  process.exit(1);
}
const run = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
console.log(run.stdout);
if (run.stderr) console.error(run.stderr);
/* Nothing is kept on success: a `lifted.rs` left on disk is the stale copy this
   script exists to make impossible. */
rmSync(dir, { recursive: true, force: true });
process.exit(run.status ?? 1);
