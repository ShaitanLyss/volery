/* Actually run `sluice.rs`'s assertions on a machine with no MSVC.
 *
 * The sluice is std-only on purpose — the emit is a closure, there is no
 * `AppHandle` and no serde in it — so the whole file lifts as it is and goes
 * straight to `rustc --test`. That matters more here than for most lifts: half
 * of what is asserted is *threads* (the flusher's bound on emits, `flush`
 * putting pending lines ahead of what follows, the thread letting go when the
 * last handle does), and a typecheck says nothing about any of it.
 *
 *     bun tools/lift-sluice.ts
 *
 * Regenerates from the source file on every run and keeps nothing — see
 * `lift-servers.ts` for why a lift that can go stale is worse than none.
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { rustEnv } from "./lift-scan.ts";

const SRC = "src-tauri/src/sluice.rs";

const src = readFileSync(SRC, "utf8").replace(/\r\n/g, "\n");
if (/^use (crate|tauri|serde)/m.test(src)) {
  throw new Error(`${SRC} has grown a dependency — it is std-only so that this lift can reach it`);
}
const lift = ["//! GENERATED by tools/lift-sluice.ts — do not edit, do not keep.", src].join("\n");

const dir = mkdtempSync(join(tmpdir(), "lift-sluice-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, lift);

try {
  const build = spawnSync(
    "rustc",
    ["--test", "--edition", "2021", "-A", "dead_code", file, "-o", exe],
    /* Bare `rustc` takes the msvc default and dies on `link: extra operand`. */
    { encoding: "utf8", env: rustEnv() },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  /* Threads are the subject, so they are not serialised here: each test owns
     its own sluice and its own channel, and running them together is a better
     test of the flusher than running them one at a time. */
  const run = spawnSync(exe, [], { encoding: "utf8" });
  console.log(run.stdout);
  if (run.stderr) console.error(run.stderr);
  process.exit(run.status ?? 1);
} finally {
  try {
    rmSync(exe, { force: true });
  } catch {
    /* the exe may still be held; the temp dir goes either way */
  }
}
