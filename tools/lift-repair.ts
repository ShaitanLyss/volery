/* Actually run the repair's pure assertions on a machine with no MSVC.
 *
 * `cargo test` does not exist here — `.claude/rules/build.md` has the whole of
 * why, and the short version is that rustc reaches for a bare `link.exe` and
 * finds GNU coreutils' `link`. So `bash tools/check-gnu.sh --tests` *typechecks*
 * `repair/text.rs`'s assertions and cannot execute one of them, which is worth
 * saying out loud because a green `--tests` reads exactly like a green test run
 * and is not one.
 *
 *     bun tools/lift-repair.ts
 *
 * `repair/text.rs` has said since the day it was split out that "a scratch
 * crate that includes just this file is the only way the assertions below get
 * run there". For three weeks that sentence described a scratch crate nobody
 * had written. This is it.
 *
 * ### Why this one needs no ITEMS list
 *
 * Every other `lift-*.ts` here picks named declarations out of a file that also
 * holds `AppHandle`s and store calls, and each carries a list that can go stale.
 * `repair/text.rs` is the whole of the pure half by construction — it reaches
 * nothing in the crate, which is the entire reason it is a separate file — so
 * this lifts **the file**, and a new function added to it is tested rather than
 * quietly skipped. The only rewrites are the two that `rustc --test` on a bare
 * file cannot carry: the `serde::Serialize` derive, which would drag in serde's
 * proc macro for a field nothing here serialises, and `pub(crate)`, which has
 * no crate to be visible in.
 *
 * ### What is worth executing here rather than merely compiling
 *
 * **`path_in_command` is a heuristic over a shell line**, and a heuristic is the
 * shape that compiles under every one of its own mistakes. What it must not do
 * is name the wrong file: the note it feeds tells a card which file to stop
 * reading, and a card sent to clean something that was never dirty is worse off
 * than one told nothing. Globs, URLs, flags, redirection targets and the
 * program's own name are each one `if` away from being reported as the source
 * of a NUL, and only an assertion that runs can say they are not.
 *
 * **The note is a wire format with an agent at the other end.** It is the whole
 * feature — see sink `08de8ed3`, where the repair healed five turns and named
 * no file, so the cards read the same poisoned file again and died again. A
 * typecheck cannot see whether the sentence that breaks that loop is still in
 * the string.
 *
 * It borrows `serde_json` out of the target directory the way `lift-board.ts`
 * does, since every record is a `Value`.
 */

import { readFileSync, writeFileSync, mkdtempSync, rmSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

const TEXT = "src-tauri/src/repair/text.rs";
const DEPS = "src-tauri/target/x86_64-pc-windows-gnu/debug/deps";

const rlib = readdirSync(DEPS).find((f) => /^libserde_json-[0-9a-f]+\.rlib$/.test(f));
if (!rlib) {
  console.error(
    `no serde_json rlib in ${DEPS} — run \`bash tools/check-gnu.sh\` first so cargo builds one.`,
  );
  process.exit(1);
}

/* Normalised first: the tree is checked out with CRLF here, and every match
   below is written with the `\n` a Rust source file is read as. */
const src = readFileSync(TEXT, "utf8").replace(/\r\n/g, "\n");

/** Both rewrites, each asserted before it is made.
 *
 *  A `replaceAll` that matches nothing is how a lift starts testing something
 *  other than the file it names — the rename lands, the script goes on passing,
 *  and the thing it proved is gone. So each one has to bite. */
function strip(what: string, from: string, to: string, text: string): string {
  if (!text.includes(from)) {
    throw new Error(`${TEXT} no longer has ${what} (\`${from}\`) — has it been rewritten?`);
  }
  return text.replaceAll(from, to);
}

let body = src;
/* serde's derive is the one thing in this file that reaches outside it, and it
   is on two structs whose *fields* are what the assertions read. */
body = strip("the serde import", "use serde::Serialize;\n", "", body);
body = strip("the report derive", "#[derive(Serialize, Clone, Debug, Default, PartialEq)]", "#[derive(Clone, Debug, Default, PartialEq)]", body);
/* Nothing above this file to be visible to. */
body = strip("the crate-visible fn", "pub(crate) fn repair_text", "pub fn repair_text", body);

const lift = ["//! GENERATED by tools/lift-repair.ts — do not edit, do not keep.", body].join("\n");

const dir = mkdtempSync(join(tmpdir(), "lift-repair-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, lift);

try {
  const build = spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "-A",
      "dead_code",
      "--extern",
      `serde_json=${join(DEPS, rlib)}`,
      "-L",
      `dependency=${DEPS}`,
      file,
      "-o",
      exe,
    ],
    /* Load-bearing: bare `rustc` takes the msvc default toolchain and dies on
       `link: extra operand`, which names nothing that points at the cause.
       Two cards found this independently — sink b282b54c and 276f26ca. */
    { encoding: "utf8", env: { ...process.env, RUSTUP_TOOLCHAIN: "stable-x86_64-pc-windows-gnu" } },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const run = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
  console.log(run.stdout);
  if (run.stderr) console.error(run.stderr);
  process.exit(run.status ?? 1);
} finally {
  /* Nothing is kept on success. A `lifted.rs` left on disk is the stale copy
     this script exists to make impossible. */
  try {
    rmSync(exe, { force: true });
  } catch {
    /* the exe may still be held; the temp dir goes either way */
  }
}
