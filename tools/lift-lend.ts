/* Actually run `lend.rs`'s assertions on a machine with no MSVC.
 *
 *     bun tools/lift-lend.ts
 *
 * `cargo test` cannot run here (`.claude/rules/build.md`), so without this the
 * module that hands a card a stored credential would be proved by a typecheck
 * alone — and the decisions that matter are exactly the ones a typecheck says
 * nothing about: that an unknown or unheld credential is refused before anybody
 * is asked, that the refusal names what *is* held, that the variable names are
 * the ones tooling already reads, that the question still carries each
 * credential's reach and both buttons, and that a write's `do it` does not
 * approve a lend. Every one of those compiles perfectly when wrong.
 *
 * `lift-docket.ts`'s technique: borrow the `serde_json` rlib cargo already
 * built, flatten the lifted items into one root, and give each `crate::x` the
 * module shape the text expects. Regenerated from the source on every run.
 *
 * Not lifted, and why: `writes`, `lend` and `whoever` take an `AppHandle` and
 * read the store, the vault and the network — the *wiring*, which
 * `check-gnu` typechecks and CI runs. `creds.rs`'s cross-check that every
 * lendable id is one the panel stores is CI's for the same reason: `SERVICES`
 * carries network probes. */

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { blockAt, depsDir, rustEnv, newestRlib } from "./lift-scan.ts";

const DEPS = depsDir();

/** What comes in, per file, in declaration order. Listing what is lifted rather
 *  than what stays out: a new pure function nobody lists is simply not asserted
 *  about, while a test naming one this omits breaks the build loudly. */
const SOURCES: Array<{ file: string; items: string[] }> = [
  /* The approval gate is `docket.rs`'s, shared rather than copied, and the
     write's word is lifted so the test can assert it does not approve a lend. */
  { file: "src-tauri/src/docket.rs", items: ["const DO_IT", "fn approved"] },
  { file: "src-tauri/src/hooks.rs", items: ["const FLAG_CARD", "const FLAG_DB", "const FLAG_SECRET"] },
  {
    file: "src-tauri/src/lend.rs",
    items: [
      "const CREDENTIAL_TOOL",
      "const ASANA_TOKEN_TOOL",
      "struct Lending",
      "const LENDABLE",
      "fn lending",
      "fn ids",
      "fn credential_schema",
      "fn asana_alias_schema",
      "fn reason_schema",
      "const HAND_IT_OVER",
      "const KEEP_IT",
      "const MAX_REASON",
      "fn resolve",
      "fn reason_of",
      "fn clip",
      "fn question",
      "fn unanswered",
      "fn declined",
      "fn turn_command",
      "fn granted",
    ],
  },
];

/** Every `#[test]` in `lend.rs`. All of them are pure, which is a property of
 *  the module worth keeping: the wiring is untested here by design, so nothing
 *  that decides should drift into it. */
const TESTS = [
  "every_credential_is_found_by_its_own_id_and_no_other",
  "no_two_credentials_share_an_id_or_a_variable",
  "the_env_names_are_the_ones_tooling_already_reads",
  "an_unknown_credential_is_refused_naming_what_is_held",
  "a_credential_volery_does_not_hold_is_refused_before_anybody_is_asked",
  "asking_without_a_reason_is_refused_before_anybody_is_asked",
  "the_credential_takes_its_own_word_and_not_the_writes_one",
  "the_question_names_the_credential_its_reach_and_both_buttons",
  "a_refusal_is_an_answer_and_says_so",
  "a_grant_puts_the_variable_in_the_command_and_never_a_secret",
  "the_schema_names_every_credential_and_says_what_it_cannot_take_back",
  "the_asana_alias_is_the_same_path_with_the_credential_fixed",
];

function reader(file: string) {
  const lines = readFileSync(file, "utf8").split(/\r?\n/);
  const block = (i: number): string => blockAt(lines, i, file);
  const testsAt = (): number => {
    const at = lines.findIndex((l) => /^\s*mod tests\s*\{/.test(l));
    return at < 0 ? lines.length : at;
  };
  const find = (what: string): string => {
    const stop = testsAt();
    const re = new RegExp(`^\\s*(pub(\\([a-z]+\\))?\\s+)?${what.replace(/ /g, "\\s+")}\\b`);
    for (let i = 0; i < stop; i++) if (re.test(lines[i])) return block(i);
    throw new Error(`could not find "${what}" in ${file} — has it been renamed?`);
  };
  const findTest = (name: string): string => {
    for (let i = testsAt(); i < lines.length; i++) {
      if (new RegExp(`^\\s*fn ${name}\\s*[(<]`).test(lines[i])) return block(i);
    }
    throw new Error(`could not find test "${name}" in ${file} — has it been renamed?`);
  };
  return { find, findTest };
}

const body: string[] = [
  "//! GENERATED by tools/lift-lend.ts — do not edit, do not keep.",
  "use serde_json::{json, Value};",
  "pub mod docket { pub use super::*; }",
  "pub mod hooks { pub use super::*; }",
];
for (const { file, items } of SOURCES) {
  const { find } = reader(file);
  body.push(`// ---- ${file} ----`, ...items.map(find));
}
const { findTest } = reader("src-tauri/src/lend.rs");
body.push("#[cfg(test)]", "mod tests {", "    use super::*;", ...TESTS.map(findTest), "}");

const dir = mkdtempSync(join(tmpdir(), "lift-lend-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, body.join("\n\n"));

try {
  const build = spawnSync(
    "rustc",
    [
      "--test",
      "--edition",
      "2021",
      "-A",
      "dead_code",
      "--extern",
      `serde_json=${newestRlib("serde_json")}`,
      "-L",
      `dependency=${DEPS}`,
      file,
      "-o",
      exe,
    ],
    { encoding: "utf8", env: { ...rustEnv() } },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const run = spawnSync(exe, { encoding: "utf8" });
  console.log(run.stdout || run.stderr);
  if (run.status !== 0) process.exit(1);
  rmSync(dir, { recursive: true, force: true });
} catch (e) {
  console.error(e);
  process.exit(1);
}
