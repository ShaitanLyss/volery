function lift(path: string, items: string[], tests: string[]): { items: string[]; tests: string[] } {
  const lines = readFileSync(path, "utf8").split(/\r?\n/);
  const block = (i: number) => blockAt(lines, i, path);
  const find = (what: string) => {
    const re = new RegExp(`^\\s*(pub(\\([a-z]+\\))?\\s+)?${what.replace(/ /g, "\\s+")}\\b`);
    for (let i = 0; i < lines.length; i++) if (re.test(lines[i])) return block(i);
    throw new Error(`could not find "${what}" in ${path} — has it been renamed?`);
  };
  const findTest = (name: string) => {
    for (let i = 0; i < lines.length; i++) {
      if (new RegExp(`^\\s*fn ${name}\\s*\\(`).test(lines[i])) return block(i);
    }
    throw new Error(`could not find test "${name}" in ${path} — has it been renamed?`);
  };
  return { items: items.map(find), tests: tests.map(findTest) };
}

const parts = Object.entries(FILES).map(([path, spec]) => lift(path, spec.items, spec.tests));

const body = [
  "//! GENERATED by tools/lift-load.ts — do not edit, do not keep.",
  ...parts.flatMap((p) => p.items),
  "#[cfg(test)]",
  "mod tests {",
  "    use super::*;",
  "    const GIB: u64 = 1024 * 1024 * 1024;",
  "    fn s(at: i64, used: u64, total: u64, cpu: f32) -> Sample { Sample { at, used, total, cpu } }",
  ...parts.flatMap((p) => p.tests),
  "}",
].join("\n\n");


const dir = mkdtempSync(join(tmpdir(), "lift-load-"));
const file = join(dir, "lifted.rs");
const exe = join(dir, "lifted.exe");
writeFileSync(file, body);

try {
  const build = spawnSync(
    "rustc",
    [
      "--test", "--edition", "2021", "-A", "dead_code", "-A", "unused_imports",
      file, "-o", exe,
    ],
    /* gnu, named: this lift borrows no rlib, so there is no tree for `rustEnv` to
       match, and its fallback is the msvc default this machine cannot link. */
    { encoding: "utf8", env: { ...rustEnv(), RUSTUP_TOOLCHAIN: "stable-x86_64-pc-windows-gnu" } },
  );
  if (build.status !== 0) {
    console.error(build.stderr || build.stdout);
    console.error(`\nthe lift is at ${file} — it was NOT removed, so you can read it.`);
    process.exit(1);
  }
  const run = spawnSync(exe, ["--test-threads", "1"], { encoding: "utf8" });
  console.log(run.stdout);
  if (run.stderr) console.error(run.stderr);
  process.exit(run.status ?? 1);
} finally {
  try {
    rmSync(exe, { force: true });
  } catch {
    /* the exe may still be held; the temp dir goes either way */
  }
}
