/* Actually run the resource guard's pure assertions on a machine with no MSVC.
 *
 *     bun tools/lift-load.ts
 *
 * Three files, because the decisions that can kill a process or strip a card's
 * tools are spread over three: `load.rs` decides what a heavy check *is* and when
 * the machine is saturated, `perf.rs::judge` decides what the reaper ends, and
 * `pool.rs` decides how a shared server is started and addressed. Every one of
 * those is a decision a typecheck cannot see the direction of — a `judge` that
 * returned `Orphan` for everything compiles, and ends every card's dev server.
 * The blocker an adversarial review found before this shipped (a card's own
 * `claude.exe` read as a test run because its system prompt mentions one) is an
 * assertion here, and it is the kind only running it can hold.
 *
 * Regenerated from source on every run and nothing kept — `lift-servers.ts`
 * says why. What it cannot reach: anything holding an `AppHandle`, a `System`
 * or a `Process` (the census, the sweep's fact gathering, `heavy_argv` itself,
 * which only wraps `heavy_simple` over a process's argv).
 */

